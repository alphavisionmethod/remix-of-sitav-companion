// ═══════════════════════════════════════════════════════════════
// SITA OS — Phase 10: Server-side PDF generator for invoices
// & signed contracts.
//
// Action: "invoice" → renders invoice PDF, uploads to
//   business-documents/{userId}/invoices/{invoiceId}.pdf,
//   stamps invoice metadata.pdf_path + emits receipt.
// Action: "contract" → renders signed contract PDF after e-sign,
//   uploads to business-documents/{userId}/signed/{signatureId}.pdf.
// ═══════════════════════════════════════════════════════════════

import { PDFDocument, StandardFonts, rgb } from "https://esm.sh/pdf-lib@1.17.1";
import { createClient } from "https://esm.sh/@supabase/supabase-js@2.45.0";
import { withCors } from "../_shared/cors.ts";
import { requireAuth } from "../_shared/auth.ts";
import { z, zodValidate } from "../_shared/zod-validate.ts";

const ActionSchema = z.discriminatedUnion("action", [
  z.object({ action: z.literal("invoice"), invoice_id: z.string().uuid() }),
  z.object({
    action: z.literal("contract"),
    signature_id: z.string().uuid(),
  }),
]);

function fmtMoney(cents: number, currency = "USD"): string {
  return new Intl.NumberFormat("en-US", { style: "currency", currency }).format((cents || 0) / 100);
}

function clean(text: unknown, max = 500): string {
  // pdf-lib's StandardFonts only render WinAnsi (Latin-1). Strip
  // anything else so we never crash mid-render on emoji/CJK.
  return String(text ?? "")
    .replace(/[^\x20-\x7E\n\r\t£€¥©®°±×÷]/g, "?")
    .slice(0, max);
}

async function buildInvoicePdf(inv: Record<string, unknown>, customerLabel: string, recipientEmail: string | null): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  const page = pdf.addPage([612, 792]); // US Letter
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);

  const ink = rgb(0.1, 0.1, 0.12);
  const muted = rgb(0.45, 0.45, 0.5);
  const accent = rgb(0.36, 0.27, 0.78);

  let y = 740;
  page.drawText("INVOICE", { x: 50, y, size: 24, font: bold, color: ink });
  page.drawText(`#${clean(inv.invoice_number, 60)}`, { x: 50, y: y - 20, size: 11, font, color: muted });

  const issued = inv.issued_at ? new Date(String(inv.issued_at)).toLocaleDateString() : new Date(String(inv.created_at)).toLocaleDateString();
  const due = inv.due_at ? new Date(String(inv.due_at)).toLocaleDateString() : "—";
  page.drawText(`Issued: ${issued}`, { x: 420, y, size: 10, font, color: muted });
  page.drawText(`Due: ${due}`, { x: 420, y: y - 14, size: 10, font, color: muted });

  // Bill-to box
  y -= 70;
  page.drawRectangle({ x: 50, y: y - 10, width: 512, height: 60, color: rgb(0.97, 0.97, 0.99) });
  page.drawText("BILL TO", { x: 60, y: y + 35, size: 8, font: bold, color: muted });
  page.drawText(clean(customerLabel, 80), { x: 60, y: y + 18, size: 13, font: bold, color: ink });
  if (recipientEmail) page.drawText(clean(recipientEmail, 80), { x: 60, y: y + 2, size: 10, font, color: muted });

  // Line items
  y -= 50;
  page.drawText("DESCRIPTION", { x: 50, y, size: 8, font: bold, color: muted });
  page.drawText("QTY", { x: 360, y, size: 8, font: bold, color: muted });
  page.drawText("UNIT", { x: 420, y, size: 8, font: bold, color: muted });
  page.drawText("AMOUNT", { x: 510, y, size: 8, font: bold, color: muted });
  y -= 6;
  page.drawLine({ start: { x: 50, y }, end: { x: 562, y }, thickness: 0.5, color: muted });

  const items = Array.isArray(inv.line_items) ? inv.line_items as Array<Record<string, unknown>> : [];
  const currency = String(inv.currency || "USD");
  for (const li of items) {
    if (y < 120) break;
    y -= 18;
    const qty = Number(li.quantity ?? 0);
    const unit = Number(li.unit_price_cents ?? 0);
    page.drawText(clean(li.description, 60), { x: 50, y, size: 10, font, color: ink });
    page.drawText(String(qty), { x: 360, y, size: 10, font, color: ink });
    page.drawText(fmtMoney(unit, currency), { x: 420, y, size: 10, font, color: ink });
    page.drawText(fmtMoney(qty * unit, currency), { x: 510, y, size: 10, font, color: ink });
  }

  // Total
  y -= 28;
  page.drawLine({ start: { x: 380, y: y + 14 }, end: { x: 562, y: y + 14 }, thickness: 0.5, color: muted });
  page.drawText("TOTAL DUE", { x: 380, y, size: 9, font: bold, color: muted });
  page.drawText(fmtMoney(Number(inv.amount_cents || 0), currency), {
    x: 480, y: y - 4, size: 18, font: bold, color: accent,
  });

  // Footer / evidence stamp
  page.drawText(
    `Generated by SITA OS · ${new Date().toISOString()} · Document hash will be receipt-anchored`,
    { x: 50, y: 30, size: 7, font, color: muted },
  );

  return await pdf.save();
}

async function buildSignedContractPdf(sig: Record<string, unknown>, source: { title: string; body: string }): Promise<Uint8Array> {
  const pdf = await PDFDocument.create();
  const page = pdf.addPage([612, 792]);
  const font = await pdf.embedFont(StandardFonts.Helvetica);
  const bold = await pdf.embedFont(StandardFonts.HelveticaBold);
  const cursive = await pdf.embedFont(StandardFonts.TimesRomanItalic);

  const ink = rgb(0.1, 0.1, 0.12);
  const muted = rgb(0.45, 0.45, 0.5);
  const accent = rgb(0.18, 0.55, 0.32);

  let y = 750;
  page.drawText(clean(source.title, 80), { x: 50, y, size: 18, font: bold, color: ink });
  page.drawText("Executed agreement", { x: 50, y: y - 18, size: 9, font, color: muted });

  // Body — wrap naive at ~95 chars
  y -= 50;
  const body = clean(source.body, 4000);
  const lines = body.split(/\r?\n/).flatMap((ln) => {
    const out: string[] = [];
    let rest = ln;
    while (rest.length > 95) {
      const cut = rest.lastIndexOf(" ", 95);
      out.push(rest.slice(0, cut > 40 ? cut : 95));
      rest = rest.slice(cut > 40 ? cut + 1 : 95);
    }
    out.push(rest);
    return out;
  });
  for (const ln of lines) {
    if (y < 200) { page.drawText("...", { x: 50, y, size: 10, font, color: muted }); break; }
    page.drawText(ln, { x: 50, y, size: 10, font, color: ink });
    y -= 14;
  }

  // Signature block
  y = 170;
  page.drawLine({ start: { x: 50, y: y + 30 }, end: { x: 562, y: y + 30 }, thickness: 0.5, color: muted });
  page.drawText("SIGNATURE", { x: 50, y, size: 8, font: bold, color: muted });
  page.drawText(clean(sig.typed_signature, 80), { x: 50, y: y - 30, size: 24, font: cursive, color: accent });
  page.drawLine({ start: { x: 50, y: y - 38 }, end: { x: 300, y: y - 38 }, thickness: 0.5, color: ink });
  page.drawText(`Signed by: ${clean(sig.signer_name || sig.signer_email, 80)}`, { x: 50, y: y - 52, size: 9, font, color: muted });

  // Audit trail
  y -= 80;
  page.drawText("AUDIT TRAIL", { x: 50, y, size: 8, font: bold, color: muted });
  y -= 12;
  const trail = [
    `Signed at: ${sig.signed_at ?? new Date().toISOString()}`,
    `Signer IP: ${clean(sig.signer_ip || "unknown", 60)}`,
    `User agent: ${clean(sig.signer_user_agent || "unknown", 90)}`,
    `Signature record: ${sig.id}`,
  ];
  for (const ln of trail) {
    page.drawText(ln, { x: 50, y, size: 8, font, color: muted });
    y -= 11;
  }

  return await pdf.save();
}

Deno.serve(withCors("business-pdf-generate", async (req, ctx) => {
  const auth = await requireAuth(req);
  if (auth instanceof Response) return auth;
  const { user, supabase } = auth;

  let raw: unknown;
  try { raw = await req.json(); } catch { return ctx.error("Invalid JSON body", 400); }
  const v = zodValidate(raw, ActionSchema);
  if (!v.success) return v.response;
  const d = v.data;

  // Service-role client for storage uploads + receipts
  const SUPABASE_URL = Deno.env.get("SUPABASE_URL")!;
  const SERVICE_ROLE = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!;
  const svc = createClient(SUPABASE_URL, SERVICE_ROLE);

  if (d.action === "invoice") {
    const { data: inv, error } = await supabase
      .from("invoices")
      .select("*, customers(display_name, primary_email), crm_contacts(display_name, primary_email), crm_companies(name)")
      .eq("id", d.invoice_id)
      .eq("user_id", user.id)
      .maybeSingle();
    if (error) return ctx.error(error.message, 500);
    if (!inv) return ctx.error("Invoice not found", 404);

    const customerLabel =
      (inv.customers as { display_name?: string } | null)?.display_name ??
      (inv.crm_contacts as { display_name?: string } | null)?.display_name ??
      (inv.crm_companies as { name?: string } | null)?.name ?? "Customer";
    const recipientEmail =
      (inv.customers as { primary_email?: string } | null)?.primary_email ??
      (inv.crm_contacts as { primary_email?: string } | null)?.primary_email ?? null;

    const bytes = await buildInvoicePdf(inv as Record<string, unknown>, customerLabel, recipientEmail);
    const path = `${user.id}/invoices/${inv.id}.pdf`;

    const upload = await svc.storage.from("business-documents").upload(path, bytes, {
      contentType: "application/pdf",
      upsert: true,
    });
    if (upload.error) return ctx.error(`Storage upload failed: ${upload.error.message}`, 500);

    const signed = await svc.storage.from("business-documents").createSignedUrl(path, 60 * 60);

    // Stamp invoice metadata with PDF reference
    const prevMeta = (inv.metadata && typeof inv.metadata === "object") ? inv.metadata as Record<string, unknown> : {};
    await supabase.from("invoices").update({
      metadata: { ...prevMeta, pdf_path: path, pdf_generated_at: new Date().toISOString(), pdf_byte_size: bytes.length },
    }).eq("id", inv.id).eq("user_id", user.id);

    // Verifiable evidence trail — receipts table
    await svc.from("receipts").insert({
      user_id: user.id,
      receipt_class: "business",
      subject_type: "invoice",
      subject_id: inv.id,
      actor_user_id: user.id,
      actor_kind: "user",
      action_key: "invoice.pdf.generated",
      outcome: "success",
      payload: {
        invoice_number: inv.invoice_number,
        amount_cents: inv.amount_cents,
        currency: inv.currency,
      },
      evidence: {
        storage_bucket: "business-documents",
        storage_path: path,
        byte_size: bytes.length,
        renderer: "pdf-lib@1.17.1",
        page_count: 1,
      },
    });

    await supabase.from("audit_logs").insert({
      user_id: user.id, action: "invoice_pdf_generated", category: "finance",
      actor: "business-pdf-generate", target_type: "invoice", target_id: inv.id,
      severity: "low", details: { path, byte_size: bytes.length },
    });

    return ctx.json({
      ok: true,
      invoice_id: inv.id,
      invoice_number: inv.invoice_number,
      pdf_path: path,
      signed_url: signed.data?.signedUrl ?? null,
      expires_in_seconds: 3600,
      byte_size: bytes.length,
    });
  }

  // Action: contract
  const { data: sig, error: sigErr } = await supabase
    .from("document_signatures")
    .select("*")
    .eq("id", d.signature_id)
    .eq("user_id", user.id)
    .maybeSingle();
  if (sigErr) return ctx.error(sigErr.message, 500);
  if (!sig) return ctx.error("Signature not found", 404);
  if (sig.status !== "signed") return ctx.error("Signature is not yet executed", 400);

  // Load source proposal/contract
  let title = "Agreement";
  let body = "";
  if (sig.document_type === "proposal" || sig.document_type === "contract") {
    const { data: prop } = await supabase
      .from("proposals")
      .select("title, scope, content")
      .eq("id", sig.document_id)
      .eq("user_id", user.id)
      .maybeSingle();
    if (prop) {
      title = prop.title || "Agreement";
      const c = prop.content as Record<string, unknown> | null;
      body = String((c?.body as string | undefined) ?? prop.scope ?? "");
    }
  }

  const bytes = await buildSignedContractPdf(sig as Record<string, unknown>, { title, body });
  const path = `${user.id}/signed/${sig.id}.pdf`;

  const up = await svc.storage.from("business-documents").upload(path, bytes, {
    contentType: "application/pdf", upsert: true,
  });
  if (up.error) return ctx.error(`Storage upload failed: ${up.error.message}`, 500);

  const signed = await svc.storage.from("business-documents").createSignedUrl(path, 60 * 60);

  await svc.from("document_signatures").update({ signed_pdf_path: path }).eq("id", sig.id);

  await svc.from("receipts").insert({
    user_id: user.id,
    receipt_class: "business",
    subject_type: sig.document_type,
    subject_id: sig.document_id,
    actor_user_id: user.id,
    actor_kind: "user",
    action_key: "esign.signed_pdf.generated",
    outcome: "success",
    payload: { signature_id: sig.id, signer_email: sig.signer_email },
    evidence: { storage_bucket: "business-documents", storage_path: path, byte_size: bytes.length, renderer: "pdf-lib@1.17.1" },
  });

  return ctx.json({
    ok: true, signature_id: sig.id, pdf_path: path,
    signed_url: signed.data?.signedUrl ?? null, expires_in_seconds: 3600, byte_size: bytes.length,
  });
}));
