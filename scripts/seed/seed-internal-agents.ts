#!/usr/bin/env -S npx tsx
/* eslint-disable no-console */
// ═══════════════════════════════════════════════════════════════
// SITA OS — Phase 2: Seed Internal Agent Definitions
//
// Reads canonical specs from src/lib/internal-agents/agents/*.ts
// and emits an idempotent SQL upsert script + a JSON manifest.
//
// Outputs:
//   generated/internal-ai-runtime-phase1/seed.sql
//   generated/internal-ai-runtime-phase1/seed-payload.json
//
// To apply seed:
//   1. Generate:  npx tsx scripts/seed/seed-internal-agents.ts
//   2. Apply via supabase--insert tool (handled by the deployment loop)
// ═══════════════════════════════════════════════════════════════

import { mkdirSync, writeFileSync } from "node:fs";
import { ALL_DETAILED_AGENTS } from "../../src/lib/internal-agents/agents/index";
import type { InternalAgentDefinition } from "../../src/lib/internal-agents/types";
import { createHash } from "node:crypto";

const OUT_DIR = "generated/internal-ai-runtime-phase1";
mkdirSync(OUT_DIR, { recursive: true });

// ── Schedule → cron mapping ────────────────────────────────────
function scheduleToCron(s: string): string {
  switch (s) {
    case "continuous": return "*/5 * * * *";   // every 5 min
    case "hourly":     return "0 * * * *";
    case "daily":      return "0 6 * * *";     // 06:00 UTC
    case "on-event":   return "0 */6 * * *";   // poll every 6h as fallback
    default:           return "0 6 * * *";
  }
}

// ── Per-agent budget heuristic (cents/day) ─────────────────────
function dailyCostCents(a: InternalAgentDefinition): number {
  switch (a.schedule) {
    case "continuous": return 200;
    case "hourly":     return 100;
    case "daily":      return 50;
    default:           return 30;
  }
}
function maxInvocationsPerDay(a: InternalAgentDefinition): number {
  switch (a.schedule) {
    case "continuous": return 288;  // every 5 min
    case "hourly":     return 24;
    case "daily":      return 4;
    default:           return 8;
  }
}
function primaryEscalation(a: InternalAgentDefinition): string {
  return a.escalationTargets?.[0] || "chief-of-staff";
}
function specHash(a: InternalAgentDefinition): string {
  return createHash("sha256")
    .update(JSON.stringify({
      id: a.agentId, council: a.council, mission: a.mission,
      max: a.maxAutonomyLevel, schedule: a.schedule, maturity: a.maturity,
    }))
    .digest("hex").slice(0, 16);
}

function sqlEscape(s: string): string {
  return s.replace(/'/g, "''");
}
function sqlJson(v: unknown): string {
  return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
}

// ── Build payload ──────────────────────────────────────────────
const payload = ALL_DETAILED_AGENTS.map((a) => ({
  agent_id: a.agentId,
  name: a.name,
  council: a.council,
  mission: a.mission,
  special_ability: a.specialAbility,
  max_autonomy_level: a.maxAutonomyLevel,
  current_autonomy_level: a.maxAutonomyLevel === "constrained_action_ready"
    ? "approval_ready" // safety: never start at the highest
    : a.maxAutonomyLevel === "approval_ready"
      ? "recommend"
      : a.maxAutonomyLevel,
  schedule_type: a.schedule,
  schedule_cron: scheduleToCron(a.schedule),
  scope: a.scope,
  out_of_scope: a.outOfScope,
  tools_allowed: a.toolsAllowed,
  tools_forbidden: a.toolsForbidden,
  memory_scope: a.memoryScope,
  trigger_conditions: a.triggerConditions,
  trigger_events: a.triggerEvents,
  escalation_targets: a.escalationTargets,
  receives_escalations_from: a.receivesEscalationsFrom,
  primary_escalation_target: primaryEscalation(a),
  confidence_threshold_act: a.confidenceRules.minConfidenceToAct,
  confidence_threshold_recommend: a.confidenceRules.minConfidenceToRecommend,
  simulation_requirements: a.simulationRequirements,
  human_approval_requirements: a.humanApprovalRequirements,
  rollback_authority: a.rollbackAuthority,
  reporting_outputs: a.reportingOutputs,
  measurable_kpis: a.measurableKpis,
  cost_budget_guidance: a.costBudgetGuidance,
  cost_budget_daily_cents: dailyCostCents(a),
  max_invocations_per_day: maxInvocationsPerDay(a),
  failure_handling_rules: a.failureHandlingRules,
  related_services: a.relatedServices,
  related_docs: a.relatedDocs,
  tags: a.tags,
  maturity: a.maturity,
  is_active: true,
  spec_hash: specHash(a),
}));

writeFileSync(
  `${OUT_DIR}/seed-payload.json`,
  JSON.stringify({ generatedAt: new Date().toISOString(), count: payload.length, agents: payload }, null, 2),
);

// ── Build idempotent SQL ───────────────────────────────────────
const sqlLines: string[] = [
  "-- Auto-generated by scripts/seed/seed-internal-agents.ts",
  "-- Phase 2: Internal AI Workforce Seed Bridge (40 agents)",
  "-- Idempotent: ON CONFLICT (agent_id) updates spec but preserves operator-controlled fields",
  "BEGIN;",
];

for (const a of payload) {
  sqlLines.push(`
INSERT INTO public.internal_agent_definitions (
  agent_id, name, council, mission, special_ability,
  max_autonomy_level, current_autonomy_level,
  schedule_type, schedule_cron,
  scope, out_of_scope, tools_allowed, tools_forbidden,
  memory_scope, trigger_conditions, trigger_events,
  escalation_targets, receives_escalations_from, primary_escalation_target,
  confidence_threshold_act, confidence_threshold_recommend,
  simulation_requirements, human_approval_requirements,
  rollback_authority, reporting_outputs, measurable_kpis,
  cost_budget_guidance, cost_budget_daily_cents, max_invocations_per_day,
  failure_handling_rules, related_services, related_docs, tags,
  maturity, is_active, spec_hash
) VALUES (
  '${sqlEscape(a.agent_id)}', '${sqlEscape(a.name)}', '${sqlEscape(a.council)}',
  '${sqlEscape(a.mission)}', '${sqlEscape(a.special_ability)}',
  '${sqlEscape(a.max_autonomy_level)}', '${sqlEscape(a.current_autonomy_level)}',
  '${sqlEscape(a.schedule_type)}', '${sqlEscape(a.schedule_cron)}',
  ${sqlJson(a.scope)}, ${sqlJson(a.out_of_scope)}, ${sqlJson(a.tools_allowed)}, ${sqlJson(a.tools_forbidden)},
  '${sqlEscape(a.memory_scope)}', ${sqlJson(a.trigger_conditions)}, ${sqlJson(a.trigger_events)},
  ${sqlJson(a.escalation_targets)}, ${sqlJson(a.receives_escalations_from)}, '${sqlEscape(a.primary_escalation_target)}',
  ${a.confidence_threshold_act}, ${a.confidence_threshold_recommend},
  ${sqlJson(a.simulation_requirements)}, ${sqlJson(a.human_approval_requirements)},
  '${sqlEscape(a.rollback_authority)}', ${sqlJson(a.reporting_outputs)}, ${sqlJson(a.measurable_kpis)},
  '${sqlEscape(a.cost_budget_guidance)}', ${a.cost_budget_daily_cents}, ${a.max_invocations_per_day},
  ${sqlJson(a.failure_handling_rules)}, ${sqlJson(a.related_services)}, ${sqlJson(a.related_docs)}, ${sqlJson(a.tags)},
  '${sqlEscape(a.maturity)}', ${a.is_active}, '${a.spec_hash}'
)
ON CONFLICT (agent_id) DO UPDATE SET
  name = EXCLUDED.name,
  council = EXCLUDED.council,
  mission = EXCLUDED.mission,
  special_ability = EXCLUDED.special_ability,
  max_autonomy_level = EXCLUDED.max_autonomy_level,
  schedule_type = EXCLUDED.schedule_type,
  schedule_cron = EXCLUDED.schedule_cron,
  scope = EXCLUDED.scope,
  out_of_scope = EXCLUDED.out_of_scope,
  tools_allowed = EXCLUDED.tools_allowed,
  tools_forbidden = EXCLUDED.tools_forbidden,
  memory_scope = EXCLUDED.memory_scope,
  trigger_conditions = EXCLUDED.trigger_conditions,
  trigger_events = EXCLUDED.trigger_events,
  escalation_targets = EXCLUDED.escalation_targets,
  receives_escalations_from = EXCLUDED.receives_escalations_from,
  primary_escalation_target = EXCLUDED.primary_escalation_target,
  confidence_threshold_act = EXCLUDED.confidence_threshold_act,
  confidence_threshold_recommend = EXCLUDED.confidence_threshold_recommend,
  simulation_requirements = EXCLUDED.simulation_requirements,
  human_approval_requirements = EXCLUDED.human_approval_requirements,
  rollback_authority = EXCLUDED.rollback_authority,
  reporting_outputs = EXCLUDED.reporting_outputs,
  measurable_kpis = EXCLUDED.measurable_kpis,
  cost_budget_guidance = EXCLUDED.cost_budget_guidance,
  cost_budget_daily_cents = EXCLUDED.cost_budget_daily_cents,
  max_invocations_per_day = EXCLUDED.max_invocations_per_day,
  failure_handling_rules = EXCLUDED.failure_handling_rules,
  related_services = EXCLUDED.related_services,
  related_docs = EXCLUDED.related_docs,
  tags = EXCLUDED.tags,
  maturity = EXCLUDED.maturity,
  spec_hash = EXCLUDED.spec_hash,
  updated_at = now();
`);
}

// Auto-create runtime_state rows for any seeded agent missing one
sqlLines.push(`
INSERT INTO public.internal_agent_runtime_state (agent_id, current_status, trust_score)
SELECT d.agent_id, 'idle', 0.5
FROM public.internal_agent_definitions d
LEFT JOIN public.internal_agent_runtime_state s ON s.agent_id = d.agent_id
WHERE s.agent_id IS NULL;
`);

sqlLines.push("COMMIT;");
writeFileSync(`${OUT_DIR}/seed.sql`, sqlLines.join("\n"));

console.log(`✅ Seed generated: ${payload.length} agents → ${OUT_DIR}/seed.sql`);
console.log(`   Councils: ${[...new Set(payload.map((a) => a.council))].length}`);
console.log(`   JSON manifest: ${OUT_DIR}/seed-payload.json`);
