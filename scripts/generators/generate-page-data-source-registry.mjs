#!/usr/bin/env node
// ═══════════════════════════════════════════════════════════════
// SITA OS — Page Data Source Registry Generator
// Scans src/ and outputs a typed registry of every file's
// database tables, RPC calls, and demo/mock references.
// ═══════════════════════════════════════════════════════════════
import { readFileSync, readdirSync, writeFileSync, mkdirSync } from "fs";
import { join, relative } from "path";

const SRC = "src";
const OUT = "src/lib/debug/page-data-source-registry.ts";

const FROM_RE = /\.from\(\s*['"`]([^'"`]+)['"`]\s*\)/g;
const RPC_RE = /\.rpc\(\s*['"`]([^'"`]+)['"`]/g;
const DEMO_RE = /\b(MOCK_|DEMO_)[A-Z_]{2,}/g;
const ISDEMO_RE = /isDemoMode/;

function* walk(dir, exts) {
  try {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      if (e.isDirectory()) {
        if (["node_modules","__tests__","test","tests",".git","dist","__mocks__"].includes(e.name)) continue;
        yield* walk(join(dir, e.name), exts);
      } else if (exts.some(x => e.name.endsWith(x))) {
        yield join(dir, e.name);
      }
    }
  } catch {}
}

const entries = [];
for (const f of walk(SRC, [".ts",".tsx"])) {
  const rel = relative(SRC, f);
  let content;
  try { content = readFileSync(f, "utf8"); } catch { continue; }
  
  const tables = [...new Set([...content.matchAll(FROM_RE)].map(m => m[1]))];
  const rpcs = [...new Set([...content.matchAll(RPC_RE)].map(m => m[1]))];
  const demoCount = (content.match(DEMO_RE) || []).length;
  const hasDemo = demoCount > 0 || ISDEMO_RE.test(content);
  const hasLive = tables.length > 0 || rpcs.length > 0;
  
  let type = "component";
  if (rel.startsWith("pages/")) type = "page";
  else if (rel.startsWith("hooks/")) type = "hook";
  
  let mode = "static";
  if (hasLive && hasDemo) mode = "mixed";
  else if (hasLive) mode = "live";
  else if (hasDemo) mode = "demo";

  entries.push({ path: rel, type, tables, rpcs, demoCount, liveQueries: tables.length + rpcs.length, mode });
}

const pages = entries.filter(e => e.type === "page");
const hooks = entries.filter(e => e.type === "hook");
const comps = entries.filter(e => e.type === "component");

mkdirSync("src/lib/debug", { recursive: true });

const ts = `// @ts-nocheck — Auto-generated data file, too large for TS inference
// ══════════════════════════════════════════════════════════
// AUTO-GENERATED by scripts/generators/generate-page-data-source-registry.mjs
// Re-run: node scripts/generators/generate-page-data-source-registry.mjs
// Generated: ${new Date().toISOString()}
// ══════════════════════════════════════════════════════════

export type DataMode = "live" | "demo" | "mixed" | "static";
export type FileType = "page" | "hook" | "component";

export interface DataSourceEntry {
  path: string;
  type: FileType;
  tables: string[];
  rpcs: string[];
  demoCount: number;
  liveQueries: number;
  mode: DataMode;
}

export const DATA_SOURCE_REGISTRY: DataSourceEntry[] = ${JSON.stringify(entries, null, 2)};

export const REGISTRY_STATS = {
  generatedAt: "${new Date().toISOString()}",
  totalFiles: ${entries.length},
  pages: { total: ${pages.length}, live: ${pages.filter(e=>e.mode==="live").length}, demo: ${pages.filter(e=>e.mode==="demo").length}, mixed: ${pages.filter(e=>e.mode==="mixed").length}, static: ${pages.filter(e=>e.mode==="static").length} },
  hooks: { total: ${hooks.length}, live: ${hooks.filter(e=>e.mode==="live").length} },
  components: { total: ${comps.length}, live: ${comps.filter(e=>e.mode==="live").length} },
  uniqueTables: ${[...new Set(entries.flatMap(e=>e.tables))].length},
  uniqueRpcs: ${[...new Set(entries.flatMap(e=>e.rpcs))].length},
} as const;
`;

writeFileSync(OUT, ts, "utf8");
console.log(`✅ Registry written to ${OUT} (${entries.length} entries)`);