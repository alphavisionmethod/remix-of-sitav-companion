export function getSpecialization(advisorId: string): AdvisorSpecializationContract | undefined {
  return ADVISOR_SPECIALIZATIONS[advisorId];
}

export function getAdvisorsByDomain(domain: string): AdvisorSpecializationContract[] {
  return Object.values(ADVISOR_SPECIALIZATIONS).filter(a => a.domain === domain);
}

export function getAdvisorPairs(advisorId: string): string[] {
  return ADVISOR_SPECIALIZATIONS[advisorId]?.pairedWith || [];
}

export function shouldRequireSimulation(advisorId: string): boolean {
  const spec = ADVISOR_SPECIALIZATIONS[advisorId];
  return spec?.simulationPolicy === "required-for-action";
}
