import React from "react";
import { Card, CardContent, CardHeader } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import { RefreshCw, Sparkles } from "lucide-react";
import ReactMarkdown from "react-markdown";
import { scanAIOutput } from "@/lib/core-services/security/ai-output-firewall";
import { AIStateBadge } from "./AIStateBadge";
import { AIDegradedState } from "./AIDegradedState";
import { AIReceiptLink } from "./AIReceiptLink";
import { formatFreshness, isStale } from "@/lib/ai/ai-surface-grammar";
import { isSuccessState, isDegradedState, isLoadingState } from "@/lib/ai/ai-state-types";
import type { AIResponseEnvelope } from "@/lib/ai/ai-state-types";

interface AIResponsePanelProps {
  response: AIResponseEnvelope | null;
  onRetry?: () => void;
  onAction?: () => void;
  /** Show provider/model/receipt details (admin surfaces) */
  showAdminDetails?: boolean;
  /** Show "generated by AI" disclosure */
  showDisclosure?: boolean;
  /** Custom title */
  title?: string;
  /** Stale threshold in minutes */
  staleAfterMinutes?: number;
  className?: string;
}

export function AIResponsePanel({
  response,
  onRetry,
  onAction,
  showAdminDetails = false,
  showDisclosure = true,
  title,
  staleAfterMinutes = 30,
  className,
}: AIResponsePanelProps) {
  if (!response) return null;

  // Degraded/error state
  if (isDegradedState(response.status) || response.status === "error" ||
      response.status === "rate_limited" || response.status === "payment_required" ||
      response.status.startsWith("unavailable_") || response.status.startsWith("blocked_")) {
    return (
      <AIDegradedState
        state={response.status}
        reason={response.degradedReason}
        onRetry={onRetry}
        onAction={onAction}
        className={className}
      />
    );
  }

  // Loading
  if (isLoadingState(response.status)) {
    return (
      <Card className={`bg-card border-border ${className ?? ""}`}>
        <CardContent className="flex items-center justify-center py-8">
          <AIStateBadge state={response.status} size="md" />
        </CardContent>
      </Card>
    );
  }

  // Success — run AI output firewall
  const firewallResult = scanAIOutput(response.content);
  const displayContent = firewallResult.sanitizedOutput;
  const stale = isStale(response.timestamp, staleAfterMinutes);

  return (
    <Card className={`bg-card border-border ${className ?? ""}`}>
      <CardHeader className="flex flex-row items-center justify-between gap-2 pb-2">
        <div className="flex items-center gap-2">
          {title && <h3 className="text-sm font-medium">{title}</h3>}
          <AIStateBadge state={response.status} launchLevel={response.launchHonestyClass} />
        </div>
        <div className="flex items-center gap-2">
          <span className="text-xs text-muted-foreground">
            {formatFreshness(response.timestamp)}
          </span>
          {(stale || response.fallbackOccurred) && onRetry && (
            <Button variant="ghost" size="sm" onClick={onRetry} className="h-7 gap-1">
              <RefreshCw className="h-3 w-3" /> Refresh
            </Button>
          )}
        </div>
      </CardHeader>
      <CardContent className="pt-0">
        <div className="prose prose-sm max-w-none dark:prose-invert">
          <ReactMarkdown>{displayContent}</ReactMarkdown>
        </div>

        {/* Footer */}
        <div className="flex items-center justify-between mt-4 pt-3 border-t border-border">
          <div className="flex items-center gap-2">
            {showDisclosure && (
              <span className="text-xs text-muted-foreground flex items-center gap-1">
                <Sparkles className="h-3 w-3" /> Generated by AI
              </span>
            )}
            {showAdminDetails && response.receiptId && (
              <AIReceiptLink receiptId={response.receiptId} />
            )}
          </div>
          {showAdminDetails && response.usageSummary && (
            <div className="flex items-center gap-3 text-xs text-muted-foreground">
              {response.providerUsed && <span>{response.providerUsed}</span>}
              {response.modelUsed && <span className="font-mono">{response.modelUsed}</span>}
              <span>{response.usageSummary.latencyMs}ms</span>
              {response.usageSummary.costCents > 0 && (
                <span>{response.usageSummary.costCents}¢</span>
              )}
            </div>
          )}
        </div>
      </CardContent>
    </Card>
  );
}
